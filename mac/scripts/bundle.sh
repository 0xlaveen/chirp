#!/bin/sh
# Builds mac/build/Chirp.app (LSUIElement menu-bar app) with SwiftPM and signs it.
# Needs only the Command Line Tools, no Xcode.
set -eu
cd "$(dirname "$0")/.."

IDENTITY="Chirp Local Dev"
APP="build/Chirp.app"

# SwiftPM combines both architectures, including dependency resources, into one universal product.
# A scratch directory outside ~/Documents avoids privacy prompts on unattended builds.
SCRATCH=${CHIRP_MAC_SCRATCH:-.build}
swift build -c release --arch arm64 --arch x86_64 --scratch-path "$SCRATCH"
BIN=$(swift build -c release --arch arm64 --arch x86_64 --scratch-path "$SCRATCH" --show-bin-path)

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN/ChirpMac" "$APP/Contents/MacOS/ChirpMac"
# Copy any SwiftPM resource bundles; they are looked up in Contents/Resources.
for b in "$BIN"/*.bundle; do
    [ -e "$b" ] && cp -R "$b" "$APP/Contents/Resources/"
done || true

# App icon (.icns from the 1024 px master) and the menu-bar template glyphs.
ICONSET=$(mktemp -d)/AppIcon.iconset
mkdir -p "$ICONSET"
for pt in 16 32 128 256 512; do
    sips -z $pt $pt Assets/AppIcon.png --out "$ICONSET/icon_${pt}x${pt}.png" >/dev/null
    sips -z $((pt * 2)) $((pt * 2)) Assets/AppIcon.png --out "$ICONSET/icon_${pt}x${pt}@2x.png" >/dev/null
done
iconutil -c icns "$ICONSET" -o "$APP/Contents/Resources/AppIcon.icns"
cp Assets/MenuBar*.png "$APP/Contents/Resources/"
cp Assets/ChirpGlyph.png "$APP/Contents/Resources/"

# The app accent colour (koi): compiled from Assets.xcassets into Assets.car, so Settings, Onboarding
# and Notes system controls pick it up. actool ships with Xcode, so a Command Line Tools-only build
# skips this and the app falls back to the system accent.
if ACTOOL=$(xcrun --find actool 2>/dev/null); then
    "$ACTOOL" --compile "$APP/Contents/Resources" --platform macosx --minimum-deployment-target 14.0 \
        --accent-color AccentColor --output-partial-info-plist "$(mktemp)" "$PWD/Assets.xcassets" >/dev/null
fi
# Third-party notices: FluidAudio's Apache-2.0 licence (and those it vendors) and the speaker model's CC BY 4.0
# attribution. About › Third-Party Notices… opens them.
cp -R Assets/ThirdParty "$APP/Contents/Resources/ThirdParty"

# The built-in sound packs (generated by scripts/make-sounds.swift; the app falls back to the system sounds without them).
mkdir -p "$APP/Contents/Resources/Sounds"
cp Assets/Sounds/* "$APP/Contents/Resources/Sounds/"

cat > "$APP/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleIdentifier</key><string>dev.chirp.mac</string>
    <key>CFBundleName</key><string>Chirp</string>
    <key>CFBundleDisplayName</key><string>Chirp</string>
    <key>CFBundleExecutable</key><string>ChirpMac</string>
    <key>CFBundleIconFile</key><string>AppIcon</string>
    <key>CFBundlePackageType</key><string>APPL</string>
    <key>CFBundleShortVersionString</key><string>0.1.0</string>
    <key>CFBundleVersion</key><string>1</string>
    <key>LSMinimumSystemVersion</key><string>14.0</string>
    <key>LSUIElement</key><true/>
    <key>NSHighResolutionCapable</key><true/>
    <key>NSAccentColorName</key><string>AccentColor</string>
    <key>NSMicrophoneUsageDescription</key>
    <string>Chirp streams your voice to your configured Chirp server to type what you say. Audio is kept only when you choose to keep it with a note.</string>
    <key>NSAudioCaptureUsageDescription</key>
    <string>With “Include call audio” on, Live Notes records what your Mac plays (the other people on a call) so both sides are transcribed by your configured Chirp server. Kept audio stays on this Mac.</string>
</dict>
</plist>
PLIST

if security find-identity -p codesigning | grep -q "\"$IDENTITY\""; then
    codesign --force --options runtime --entitlements scripts/Chirp.entitlements --sign "$IDENTITY" "$APP"
    echo "Signed with \"$IDENTITY\"."
else
    codesign --force --options runtime --entitlements scripts/Chirp.entitlements --sign - "$APP"
    echo "WARNING: identity \"$IDENTITY\" not found, signed ad-hoc." >&2
    echo "         macOS will forget the Microphone/Accessibility grants on every rebuild." >&2
    echo "         Run scripts/make-cert.sh once to fix that." >&2
fi
codesign --verify --strict "$APP" && echo "Built $APP"
